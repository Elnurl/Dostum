export function defaultAvailability() {
  const map: Record<string, 'free' | 'busy'> = {};
  for (let i = 0; i < 21; i += 1) {
    const key = addDaysIso(today, i);
    map[key] = i === 3 || i === 10 ? 'busy' : 'free';
  }
  map[today] = 'busy';
  map[tomorrow] = 'busy';
  return map;
}
